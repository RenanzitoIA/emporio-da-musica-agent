"""Extract the store policy PDF into clean text the agent can read.

Run once (the output is committed): python scripts/extract_policies.py
"""

import re
from pathlib import Path

from pypdf import PdfReader

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "data" / "raw" / "store_policies.pdf"
OUT = ROOT / "data" / "processed" / "store_policies.md"

NOISE = [
    re.compile(r"^Empório da Música\s+(\|\s+)?Manual de Políticas e Procedimentos$"),
    re.compile(r"^Página \d+$"),
]


def main() -> None:
    lines: list[str] = []
    for page in PdfReader(SRC).pages[1:]:  # page 1 is the cover
        # The default mode splits every word onto its own line for this PDF
        # (generated by Google Docs/Skia); layout mode keeps lines and tables.
        for line in page.extract_text(extraction_mode="layout").splitlines():
            line = re.sub(r"^[•●]\s+", "- ", line.strip())  # bullets
            line = re.sub(r"\s{3,}", "  |  ", line)  # table columns
            if not any(p.match(line) for p in NOISE):
                lines.append(line)
    text = re.sub(r"\n{3,}", "\n\n", "\n".join(lines)).strip()
    OUT.write_text(text + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text)} chars)")


if __name__ == "__main__":
    main()
